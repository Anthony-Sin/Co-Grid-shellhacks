@app.get("/api/city/{scene}")
def city(scene: str, accept_encoding: Optional[str] = Header(None)):
    if scene not in (
        "savannah",
        "augusta",
        "state",
        # metro cores — composited into the statewide view as detail
        "atlanta",
        "columbia",
        "charleston",
        "greenville_sc",
        "columbus_ga",
        "athens",
        "macon",
    ):
        raise HTTPException(404, "unknown scene")
    path = PROCESSED / f"city_{scene}.json"
    if not path.exists():
        raise HTTPException(
            503, f"city_{scene}.json not generated yet — run the processing pipeline")
    # Pre-compressed fast path: serve the cached gzip blob straight from
    # the file bytes — same JSON the dict path would serialize, minus a
    # ~20–50 MB re-encode + re-compress per request. GZipMiddleware sees
    # the Content-Encoding header and passes the body through untouched.
    if accept_encoding and "gzip" in accept_encoding:
        return Response(
            content=_gzipped(str(path), path.stat().st_mtime),
            media_type="application/json",
            headers={"Content-Encoding": "gzip", "Vary": "Accept-Encoding"},
        )
    return _fresh(f"city_{scene}.json")


