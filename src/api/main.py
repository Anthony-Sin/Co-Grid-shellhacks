@app.get("/api/regions")
def regions() -> dict:
    """Index of renderable regions/scenes — the contract for statewide tiles.
    Each entry: id, label, lon/lat bounds, center, and which artifacts exist.
    The frontend can offer scene switching/tiles off this list without
    hardcoding geography."""
    from src.processing.projection import SCENES
    out = []
    for scene, label in [
        ("savannah", "Savannah corridor"),
        ("augusta", "Augusta corridor"),
        ("atlanta", "Atlanta core"),
        ("columbia", "Columbia SC core"),
        ("charleston", "Charleston core"),
        ("greenville_sc", "Greenville SC core"),
        ("columbus_ga", "Columbus GA core"),
        ("athens", "Athens core"),
        ("macon", "Macon core"),
    ]:
        p = PROCESSED / f"city_{scene}.json"
        out.append({
            "id": scene,
            "label": label,
            "bounds": list(SCENES[scene]["bbox"]),
            "center": list(SCENES[scene]["center"]),
            "artifact": f"city_{scene}.json",
            "built": p.exists(),
            "size_mb": round(p.stat().st_size / 1e6, 1) if p.exists() else None,
        })
    # Statewide entry — basemap.geojson now covers GA+SC (~15.7k features);
    # the city_<state>.json scene lands separately (tiles, not one payload).
    bm = PROCESSED / "basemap.geojson"
    out.append({
        "id": "state",
        "label": "Georgia + South Carolina (statewide)",
        "bounds": list(SCENES["state"]["bbox"]),
        "center": list(SCENES["state"]["center"]),
        "artifact": "basemap.geojson",
        "built": bm.exists(),
        "size_mb": round(bm.stat().st_size / 1e6, 1) if bm.exists() else None,
        "city_scene": (PROCESSED / "city_state.json").exists(),
        "coverage": "existing grid statewide; planned projects corridor-focused",
    })
    # zone rollup — region tags carried by the data itself (projects.zones
    # and the derived overlap.zone labels) so a picker can scope by region.
    projs = _fresh("projects.geojson").get("features", [])
    ovs = _fresh("overlaps.json").get("overlaps", [])
    zones: dict[str, dict] = {}
    for f in projs:
        for z in f["properties"].get("zones") or []:
            zones.setdefault(z, {"id": z, "projects": 0, "overlaps": 0})
            zones[z]["projects"] += 1
    for o in ovs:
        for z in (o.get("zone") or "").split(" / "):
            if z in zones:
                zones[z]["overlaps"] += 1
    return {"regions": out, "zones": sorted(zones.values(), key=lambda z: -z["overlaps"])}


_OVERLAP_SORTS = {
    "score": lambda r: (-r.get("score", 0)),
    # 0.0 km (touching) is a real distance, not missing — test for None,
    # never `or` (falsy 0.0 used to send all tier-1 records to the end)
    "distance": lambda r: (
        r["min_distance_km"] if r.get("min_distance_km") is not None else 1e9,
        -r.get("score", 0)),
    "distance_desc": lambda r: (
        -(r["min_distance_km"] if r.get("min_distance_km") is not None else -1e9),
        -r.get("score", 0)),
    "year": lambda r: (
        (r.get("shared_window") or {}).get("start") or 9999,
        -r.get("score", 0)),
}


@app.get("/api/overlaps")
def overlaps(
    tier: Optional[int] = Query(None, ge=1, le=4),
    timeline_only: bool = Query(False),
    q: Optional[str] = Query(None, description="substring match on ids, project names, utilities"),
    zone: Optional[str] = Query(None, description="region tag — matches zone labels incl. 'a / b' pairs"),
    state: Optional[str] = Query(None, description="ga | sc — records whose zone touches that state"),
    sort: Optional[str] = Query(None, description="score | distance | distance_desc | year"),
    limit: Optional[int] = Query(None, ge=1, le=500),
    offset: int = Query(0, ge=0, description="skip N rows after filter/sort (paging)"),
    geometry: bool = Query(True, description="false drops zone_geometry polygons"),
    fields: Optional[str] = Query(
        None, description="comma-separated record keys to keep (slim payload)"),
) -> dict:
    data = _fresh("overlaps.json")
    rows = data.get("overlaps", [])
    if tier is not None:
        rows = [r for r in rows if r["tier"] == tier]
    if zone:
        z = zone.strip().lower()
        rows = [r for r in rows if z in (r.get("zone") or "").lower()]
    if state:
        from src.analysis.filters import filter_records as _fr
        try:
            rows = _fr(rows, state=state)
        except ValueError as e:
            raise HTTPException(422, str(e)) from e
    if timeline_only:
        rows = [r for r in rows if r["timeline_overlap"]]
    if q:
        needle = q.strip().lower()
        rows = [r for r in rows if needle in json.dumps({
            "id": r.get("overlap_id"), "a": r.get("project_a"),
            "b": r.get("project_b"), "u": r.get("utilities"),
            "x": r.get("explanation"),
        }).lower()]
    if sort is not None:
        if sort not in _OVERLAP_SORTS:
            raise HTTPException(422, f"unknown sort {sort!r} — use score|distance|distance_desc|year")
        rows = sorted(rows, key=_OVERLAP_SORTS[sort])
    total = len(rows)
    if offset:
        rows = rows[offset:]
    if limit is not None:
        rows = rows[:limit]
    if not geometry:
        rows = [{k: v for k, v in r.items() if k != "zone_geometry"} for r in rows]
    if fields:
        keep = {k.strip() for k in fields.split(",") if k.strip()}
        rows = [{k: r.get(k) for k in keep} for r in rows]
    return {**data, "overlaps": rows, "total": total, "offset": offset}


@app.get("/api/overlaps.csv")
def overlaps_csv(
    utility: Optional[str] = Query(None),
    utilities: Optional[str] = Query(
        None, description="exact pair, comma-separated — e.g. 'DESC,GPC'"),
    tier: Optional[int] = Query(None, ge=1, le=4),
    zone: Optional[str] = Query(None),
    state: Optional[str] = Query(None, description="ga | sc"),
    timeline_only: bool = Query(False),
    adjacent_only: bool = Query(False),
    missing_dates: bool = Query(False),
    sort: Optional[str] = Query(None, description="score | distance | distance_desc | year"),
) -> "Response":
    """Ranked overlaps as flat CSV — teammates/spreadsheets/BI friendly.
    Accepts the same filters as the agent's find_overlaps tool (shared
    filter_records) so agent-emitted csv_export links are faithful."""
    from fastapi.responses import Response
    from src.analysis.filters import filter_records
    from src.processing.projection import scene_for_zone

    rows = _fresh("overlaps.json").get("overlaps", [])
    try:
        rows = filter_records(
            rows, utility=utility, utilities=utilities, tier=tier,
            zone=zone, state=state, timeline_only=timeline_only,
            adjacent_only=adjacent_only, missing_dates=missing_dates)
    except ValueError as e:
        raise HTTPException(422, str(e)) from e
    if sort is not None:
        if sort not in _OVERLAP_SORTS:
            raise HTTPException(422, f"unknown sort {sort!r} — use score|distance|distance_desc|year")
        rows = sorted(rows, key=_OVERLAP_SORTS[sort])
    rows = list(rows)  # overlaps.json is already engine-ordered

    cols = [
        "rank", "overlap_id", "project_a", "project_b", "utilities",
        "tier", "tier_label", "zone", "min_distance_km", "timeline_overlap",
        "timeline_adjacent", "shared_window_start", "shared_window_end",
        "closest_lon", "closest_lat", "score",
        "shared_row_km", "est_savings_low_usd", "est_savings_high_usd",
        "explanation", "map_link",
    ]
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(cols)
    for i, r in enumerate(rows, 1):
        win = r.get("shared_window") or {}
        cp = r.get("closest_point_a") or [None, None]
        cost = r.get("cost") or {}
        w.writerow([
            i, r.get("overlap_id"), r.get("project_a"), r.get("project_b"),
            "|".join(r.get("utilities") or []), r.get("tier"), r.get("tier_label"),
            r.get("zone"), r.get("min_distance_km"), r.get("timeline_overlap"),
            r.get("timeline_adjacent", False),
            win.get("start"), win.get("end"), cp[0], cp[1], r.get("score"),
            cost.get("shared_row_km"), cost.get("est_savings_usd_low"),
            cost.get("est_savings_usd_high"), r.get("explanation"),
            f"/?scene={scene_for_zone(r.get('zone'))}"
            f"&select={r.get('overlap_id')}&panel=0",
        ])
    return Response(
        content=buf.getvalue(),
        media_type="text/csv",
        headers={"Content-Disposition": 'attachment; filename="co-grid-overlaps.csv"'},
    )


@app.get("/api/stats")
def stats() -> dict:
    projs = _fresh("projects.geojson").get("features", [])
    ovs = _fresh("overlaps.json").get("overlaps", [])
    by_util: dict[str, int] = {}
    by_tier: dict[str, int] = {}
    for f in projs:
        u = f["properties"].get("utility", "?")
        by_util[u] = by_util.get(u, 0) + 1
    for o in ovs:
        t = str(o["tier"])
        by_tier[t] = by_tier.get(t, 0) + 1
    out = {
        "projects": len(projs),
        "by_utility": by_util,
        "overlaps": len(ovs),
        "by_tier": by_tier,
        "timeline_matches": sum(1 for o in ovs if o["timeline_overlap"]),
        "timeline_adjacent": sum(1 for o in ovs if o.get("timeline_adjacent")),
    }
    # program-level rollup — staging regions + busiest shared season
    # (cached on overlaps.json mtime — the cluster build is O(n²))
    try:
        mtime = (PROCESSED / "overlaps.json").stat().st_mtime
        out.update(_program_rollup(mtime))
    except Exception:
        out["staging_yards"] = None
        out["staging_corridors"] = None
        out["peak_season"] = None
    # per-utility coverage: filed projects participating in >=1 overlap
    proj_ids = {
        f["properties"].get("project_id"): f["properties"].get("utility", "?")
        for f in projs
    }
    covered: dict[str, set] = {u: set() for u in by_util}
    for o in ovs:
        for pid in (o.get("project_a"), o.get("project_b")):
            u = proj_ids.get(pid)
            if u:
                covered.setdefault(u, set()).add(pid)
    out["coverage"] = {
        u: {"projects": by_util.get(u, 0),
            "in_overlaps": len(ids)}
        for u, ids in covered.items()
    }
    return out


@app.get("/api/exports/{name}")
def export_file(name: str) -> FileResponse:
    """Serve one generated export (the agent's export_data links point
    here). Names are confined to the flat exports/ dir — separators,
    traversal, and non-export extensions are all refused."""
    if "/" in name or "\\" in name or ".." in name:
        raise HTTPException(403, "bad export name")
    ext = Path(name).suffix.lower()
    if ext not in _EXPORT_MIME:
        raise HTTPException(403, "only .csv/.xlsx/.html exports are served")
    target = (EXPORTS / name).resolve()
    if not target.is_relative_to(EXPORTS.resolve()) or not target.is_file():
        raise HTTPException(404, "export not found — it may have been cleaned up")
    return FileResponse(target, media_type=_EXPORT_MIME[ext],
                        filename=name)


@app.get("/api/raw/{path:path}")
def raw_file(path: str) -> FileResponse:
    """Serve a raw filing (e.g. a downloaded PDF) — provenance links in UI."""
    raw_root = (ROOT / "data" / "raw").resolve()
    target = (raw_root / path).resolve()
    if not target.is_relative_to(raw_root):
        raise HTTPException(403, "path escapes raw data dir")
    if not target.exists():
        raise HTTPException(404, "not found")
    return FileResponse(target)
